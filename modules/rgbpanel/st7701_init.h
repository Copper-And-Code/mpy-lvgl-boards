// ST7701S init sequence for the 4" 480x480 panel of the Waveshare RP2350-Touch-LCD-4.
//
// Panel data taken from the Waveshare demo (bsp_st7701.c, as found in
// github.com/jondurrant/RP2350Touch4-Exp): register values only, re-encoded.
//
// Encoding: command, number of parameter bytes, parameters...
// A parameter count of ST7701_DELAY means "sleep for the next byte * 10 ms".

#define ST7701_DELAY (0xfe)

static const uint8_t st7701_init_seq[] = {
    // Command2 BK0
    0xff, 5, 0x77, 0x01, 0x00, 0x00, 0x10,
    0xc0, 2, 0x3b, 0x00,
    0xc1, 2, 0x0d, 0x02,
    0xc2, 2, 0x31, 0x05,
    0xcd, 1, 0x08,
    // Positive / negative voltage gamma control
    0xb0, 16, 0x00, 0x11, 0x18, 0x0e, 0x11, 0x06, 0x07, 0x08, 0x07, 0x22, 0x04, 0x12, 0x0f, 0xaa, 0x31, 0x18,
    0xb1, 16, 0x00, 0x11, 0x19, 0x0e, 0x12, 0x07, 0x08, 0x08, 0x08, 0x22, 0x04, 0x11, 0x11, 0xa9, 0x32, 0x18,
    // Command2 BK1: power
    0xff, 5, 0x77, 0x01, 0x00, 0x00, 0x11,
    0xb0, 1, 0x60, // Vop 4.7375 V
    0xb1, 1, 0x32, // VCOM
    0xb2, 1, 0x07, // VGH 15 V
    0xb3, 1, 0x80,
    0xb5, 1, 0x49, // VGL -10.17 V
    0xb7, 1, 0x85,
    0xb8, 1, 0x21, // AVDD 6.6 V, AVCL -4.6 V
    0xc1, 1, 0x78,
    0xc2, 1, 0x78,
    // GIP timing
    0xe0, 3, 0x00, 0x1b, 0x02,
    0xe1, 11, 0x08, 0xa0, 0x00, 0x00, 0x07, 0xa0, 0x00, 0x00, 0x00, 0x44, 0x44,
    0xe2, 12, 0x11, 0x11, 0x44, 0x44, 0xed, 0xa0, 0x00, 0x00, 0xec, 0xa0, 0x00, 0x00,
    0xe3, 4, 0x00, 0x00, 0x11, 0x11,
    0xe4, 2, 0x44, 0x44,
    0xe5, 16, 0x0a, 0xe9, 0xd8, 0xa0, 0x0c, 0xeb, 0xd8, 0xa0, 0x0e, 0xed, 0xd8, 0xa0, 0x10, 0xef, 0xd8, 0xa0,
    0xe6, 4, 0x00, 0x00, 0x11, 0x11,
    0xe7, 2, 0x44, 0x44,
    0xe8, 16, 0x09, 0xe8, 0xd8, 0xa0, 0x0b, 0xea, 0xd8, 0xa0, 0x0d, 0xec, 0xd8, 0xa0, 0x0f, 0xee, 0xd8, 0xa0,
    0xeb, 7, 0x02, 0x00, 0xe4, 0xe4, 0x88, 0x00, 0x40,
    0xec, 2, 0x3c, 0x00,
    0xed, 16, 0xab, 0x89, 0x76, 0x54, 0x02, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x20, 0x45, 0x67, 0x98, 0xba,
    // Command2 BK3: VAP & VAN
    0xff, 5, 0x77, 0x01, 0x00, 0x00, 0x13,
    0xe5, 1, 0xe4,
    // Back to Command1
    0xff, 5, 0x77, 0x01, 0x00, 0x00, 0x00,
    0x21, 0,       // display inversion on (IPS)
    0x3a, 1, 0x60, // 18-bit RGB interface
    0x11, 0,       // sleep out
    0x00, ST7701_DELAY, 12,
    0x29, 0,       // display on
    0x00, ST7701_DELAY, 12,
};
