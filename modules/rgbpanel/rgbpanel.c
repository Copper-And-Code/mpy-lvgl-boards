// rgbpanel: scan-out of a 480x480 RGB565 parallel panel (ST7701S) from a
// framebuffer in SRAM, for the Waveshare RP2350-Touch-LCD-4.
//
// The scan-out runs without the CPU and without interrupts:
// - PIO1 generates HSYNC/PCLK and VSYNC, PIO2 generates DE and the pixels
//   (see rgbpanel.pio);
// - a data DMA channel feeds the PIO2 TX FIFO; a control DMA channel reloads
//   it from a list of control blocks, one per transfer. The last block makes
//   the data channel rewind the control channel to the top of the list.
// - a third DMA channel drains one word per frame from lcd_vsync's RX FIFO:
//   its transfer count is the frame counter.
//
// All of it keeps running across a MicroPython soft reset: state machines,
// programs and DMA channels are claimed through the pico-sdk directly, not
// through rp2.PIO / rp2.DMA. State is in .bss, which a soft reset keeps.
//
// Double buffering (init(buffers=2)): a second framebuffer with its own list
// of control blocks lives on the GC heap. The rewind block reads the list to
// use for the next frame from rgbpanel_cb_top, so changing that pointer swaps
// buffers exactly at the end of a frame, in hardware.
//
// The framebuffer is RGBPANEL_WIDTH x RGBPANEL_HEIGHT; with
// MICROPY_HW_RGBPANEL_SCALE = 2 it is 240x240 and every pixel is shown as
// 2x2 panel pixels (horizontal doubling in PIO, vertical doubling by DMA).

